/**
 * Writes both API stand-ins from one dataset:
 *
 *   mock-api/   static JSON, published with the app so the demo link makes real
 *               network requests without a server to host
 *   mockoon/    a Mockoon environment for local development, where the same
 *               routes answer dynamically
 *
 * Run with `npm run mock:build` after editing scripts/mock-dataset.mjs.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { randomUUID } from 'node:crypto';
import {
  CONFIRMATION_FUNNEL,
  ORDERS_OVER_TIME,
  PERFORMANCE,
  RETURN_REASON_REPORT,
  STATUS_BREAKDOWN,
  SUMMARY,
} from './mock-dataset.mjs';

/** Every route the reports screen calls, with the body each one returns. */
const ROUTES = [
  { method: 'get', endpoint: 'reports/summary', body: SUMMARY },
  { method: 'get', endpoint: 'reports/orders-over-time', body: ORDERS_OVER_TIME },
  { method: 'get', endpoint: 'reports/status-breakdown', body: STATUS_BREAKDOWN },
  { method: 'get', endpoint: 'reports/returns-by-reason', body: RETURN_REASON_REPORT },
  { method: 'get', endpoint: 'reports/confirmation-funnel', body: CONFIRMATION_FUNNEL },
  ...Object.entries(PERFORMANCE).map(([dimension, data]) => ({
    method: 'get',
    endpoint: `reports/performance/${dimension}`,
    body: { group_by: dimension, data },
  })),
  {
    method: 'post',
    endpoint: 'user/login',
    body: {
      id: '123324',
      name: 'ahmed',
      email: 'ahmed.safar@gmail.com',
      phone: '01000000000',
      accessToken: 'demo-access-token',
      refreshToken: 'demo-refresh-token',
    },
  },
  { method: 'post', endpoint: 'auth/refresh', body: { accessToken: 'demo-access-token' } },
];

const write = (path, value) => {
  mkdirSync(dirname(path), { recursive: true });
  const body =
    value === null
      ? '<!-- Generated by scripts/generate-mock-api.mjs. Edit scripts/mock-dataset.mjs instead. -->\n'
      : `${JSON.stringify(value, null, 2)}\n`;
  writeFileSync(path, body);
};

// ---- static JSON -----------------------------------------------------------
// Written without a file extension, because the app asks for
// `reports/summary` and a static host serves the path exactly as requested —
// `summary.json` would simply 404. Angular parses the body as JSON from the
// request's responseType, so the absent Content-Type does not matter.
//
// A static host also ignores the query string, so `?from=…&to=…` is not
// honoured and responses do not change with the date filter in the demo.
let staticCount = 0;
for (const route of ROUTES) {
  if (route.method !== 'get') continue;
  write(join('mock-api', route.endpoint), route.body);
  staticCount += 1;
}
// POST cannot be served by a static host at all; the demo build skips the login
// screen (see auth.guard.ts), so those routes exist only in Mockoon.
write(join('mock-api', 'README.md'), null);

// ---- Mockoon environment ---------------------------------------------------
const mockoon = {
  uuid: '8db2f909-8a81-4af6-a719-610168899368',
  lastMigration: 33,
  name: 'Drivoo Reports API',
  endpointPrefix: 'api/v1/',
  latency: 0,
  port: 3000,
  hostname: '',
  folders: [],
  routes: ROUTES.map((route) => ({
    uuid: randomUUID(),
    type: 'http',
    documentation: '',
    method: route.method,
    endpoint: route.endpoint,
    responses: [
      {
        uuid: randomUUID(),
        body: JSON.stringify(route.body, null, 2),
        latency: 0,
        statusCode: 200,
        label: '',
        headers: [],
        bodyType: 'INLINE',
        filePath: '',
        databucketID: '',
        sendFileAsBody: false,
        rules: [],
        rulesOperator: 'OR',
        disableTemplating: true,
        fallbackTo404: false,
        default: true,
        crudKey: 'id',
        callbacks: [],
      },
    ],
    responseMode: null,
    streamingMode: null,
    streamingInterval: 0,
  })),
  rootChildren: [],
  proxyMode: false,
  proxyHost: '',
  proxyRemovePrefix: false,
  tlsOptions: { enabled: false, type: 'CERT', pfxPath: '', certPath: '', keyPath: '', caPath: '', passphrase: '' },
  cors: true,
  headers: [
    { key: 'Content-Type', value: 'application/json' },
    { key: 'Access-Control-Allow-Origin', value: '*' },
    { key: 'Access-Control-Allow-Methods', value: 'GET,POST,PUT,PATCH,DELETE,HEAD,OPTIONS' },
    { key: 'Access-Control-Allow-Headers', value: 'Content-Type, Origin, Accept, Authorization, Content-Length, X-Requested-With' },
  ],
  proxyReqHeaders: [{ key: '', value: '' }],
  proxyResHeaders: [{ key: '', value: '' }],
  data: [],
  callbacks: [],
};
mockoon.rootChildren = mockoon.routes.map((route) => ({ type: 'route', uuid: route.uuid }));
write(join('mockoon', 'drivoo-api.json'), mockoon);

console.log(`static JSON files: ${staticCount}`);
console.log(`mockoon routes:    ${mockoon.routes.length}`);
